// 洛谷 P4414 [COCI2006-2007#2] ABC
// https://www.luogu.com.cn/problem/P4414
// 备注：解法二 · 查表法（sort + 字母当下标）
//       排序后 x[0] < x[1] < x[2]，天然就是 A、B、C 的顺序；
//       用 ch - 'A' 把字母换算成 0/1/2 的下标，直接查数组。
//
// 心得（把"按名字找"换成"按编号找"）：
//       解法一用 if 逐个比对字母，本质是"按名字找变量"；
//       这里把三个数放进数组，字母靠 ASCII 码相减得到下标，
//       变成"按编号找格子"。分支不随字母数量增长——以后遇到
//       26 个字母或者一张对照表，就不用写一长串 if。
//       代价是多一层下标换算，且依赖 'A'~'Z' 编码连续这个前提。
//       三个字母的题两版都行，怎么写一来看场景、二来看顺手。
//
//       本题 val 和 x 的内容完全相同，保留 val 只是为了把
//       "先建对照表、再按字母查" 这个结构写清楚。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int x[3];
    cin >> x[0] >> x[1] >> x[2];
    sort(x, x + 3);                 // x[0] 最小，x[1] 中间，x[2] 最大

    int val[3];
    val[0] = x[0];                  // A
    val[1] = x[1];                  // B
    val[2] = x[2];                  // C

    string s;
    cin >> s;                       // 第二行，如 "CBA"

    for (char ch : s) {
        cout << val[ch - 'A'] << ' ';
    }
    cout << '\n';
    return 0;
}
