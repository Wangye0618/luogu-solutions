// 洛谷 P1075 [NOIP2012 普及组] 质因数分解
// https://www.luogu.com.cn/problem/P1075
// 备注：题目保证 n 是两个「不同质数」之积，设 n = p × q（p < q）。
//       那 n 的因子只有 1、p、q、n —— 所以从 2 开始找，
//       第一个能整除 n 的 b 一定是较小的质数 p，答案就是 n / p。
//
//       为什么要枚举到 √n 就够（本题甚至没写这个上界，但也没慢）：
//       p ≤ q  →  p ≤ √n。n ≤ 2×10^9 时 √n ≈ 44721，
//       所以循环一定在 b = p ≤ 44721 时就 break，走不到 b = n。
//
//       这是枚举法的第二次应用（第一次是 P4956）：
//         ① 枚举什么：因子 b
//         ② 范围：2 → 最多 44721
//         ③ 验证：n % b == 0
//         ④ 停止：第一个能整除的
//
//       上界写成 b < n 而不是 for(;;)，是个防御习惯：
//       万一 n 不是「两质数之积」（比如 n 本身是质数），也不会死循环。
//
//       注意：n ≤ 2×10^9 而 int 上限约 2.147×10^9，刚好装得下；
//       若题目再大一点（如 3×10^9）就必须换 long long。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n;
    cin >> n;

    for (int b = 2; b < n; b++) {
        if (n % b == 0) {
            cout << n / b << endl;   // b 是较小的质数，另一个因子是答案
            break;
        }
    }
    return 0;
}
