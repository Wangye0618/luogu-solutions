// 洛谷 P1420 最长连号
// https://www.luogu.com.cn/problem/P1420
// 备注：滚动变量。数组版里 a[i] 只和 a[i-1] 比较，所以 a[0..i-2] 全都是废数据，
//       只需要一个变量 b 记住「上一个数」就够了 —— O(1) 空间代替 O(n) 数组。
//
//       cn   当前这段连号的长度（断了就重置为 1）
//       best 历史最长（每轮和 cn 比一次）
//       b    上一个读入的数（每轮读完立刻更新，注意要放在 if 外面，
//            否则第 1 个数不会进 b，第 2 轮比较就用错了初值 0）
//
//       踩过的坑：
//       1) 一开始把「和上一个比」写成了 while (i >= 2) —— i 在 while 里不变 → 死循环。
//          这里一次循环只比较一次，应该用 if。
//       2) 忘了 cin >> n，n 是垃圾值。
//       3) cn 初值写成 0（应该是 1，单个数字也是长度 1）。
//       4) 只输出 cn（最后一段），没记 best（历史最长）。
//          这个 bug 只有在「最长段在中间、后面还有更短的段」时才暴露，
//          例如 1 2 3 5 6：正确 3，只输出 cn 会得到 2。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n, a, b = 0;
    int cn = 1, best = 1;        // 连号长度至少为 1

    cin >> n;

    for (int i = 1; i <= n; i++) {
        cin >> a;

        if (i >= 2) {                    // 从第 2 个数开始才有「上一个」可比
            if (b == a - 1) {
                cn++;                    // 连号延续
            } else {
                cn = 1;                  // 断了，重新开始
            }
            if (cn > best) best = cn;    // 记录历史最长
        }

        b = a;                           // 更新「上一个」，每轮都要做
    }

    cout << best << endl;
    return 0;
}
