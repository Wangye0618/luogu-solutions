// 洛谷 P1307 [NOIP2011 普及组] 数字反转
// https://www.luogu.com.cn/problem/P1307
// 备注：核心三步 —— 取末位、接到结果后面、去掉末位。
//         rev = rev * 10 + n % 10;   // 把末位接到 rev 后面
//         n /= 10;                   // 去掉末位
//
//       关键 ①：循环条件写 while (n != 0)，不要写 while (n > 0)。
//       因为 C++ 里 % 的符号跟着被除数，负数会被自动处理：
//         n = -380 → n%10 = 0   → rev = 0
//                  → n%10 = -8  → rev = -8
//                  → n%10 = -3  → rev = -83    ✅ 负号自己跟着走
//       所以不需要 abs()、不需要符号变量、不需要任何 if。
//
//       关键 ②：rev 必须初始化成 0。局部变量不会自动清零，
//       `rev = rev * 10 + ...` 从垃圾值开始算，结果全错。
//
//       踩过的坑：
//       - 写成 while (N > 0)，负数一次都不进循环
//       - 想用 if (N < 0) 事后补救，但循环结束时 N 已经变成 0 了，这个 if 永远不成立
//       - 结果对正数什么都不输出、对负数输出垃圾
//       - rev（当时叫 a）没初始化

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n = 0, rev = 0;          // 两个都初始化
    cin >> n;

    while (n != 0) {             // != 0 而不是 > 0，负数也能进
        rev = rev * 10 + n % 10; // 把末位接到 rev 后面
        n /= 10;                 // 去掉末位
    }

    cout << rev << endl;
    return 0;
}
