// 洛谷 P1428 小鱼比可爱
// https://www.luogu.com.cn/problem/P1428
// 备注：对每条鱼 i，数它前面（j < i）有几条鱼的可爱值比它小（a[j] < a[i]）。
//
//       读题三问（这题的关键）：
//         ① 和谁比？  → 和 a[i]（当前这条鱼）比
//         ② 哪些？    → j 从 1 到 i-1（前面所有鱼）
//         ③ 数什么？  → 数个数，不是数连续
//
//       走样例 4 3 0 5 1 2：
//         鱼1(4) 前面没鱼                        → 0
//         鱼2(3) 前面 4，4<3 否                  → 0
//         鱼3(0) 前面 4,3，都否                  → 0
//         鱼4(5) 前面 4,3,0，三个都小            → 3
//         鱼5(1) 前面 4,3,0,5，只有 0 小         → 1
//         鱼6(2) 前面 4,3,0,5,1，0 和 1 小       → 2
//         输出 0 0 0 3 1 2
//
//       踩过的坑（读题偏差，比语法错更难发现 —— 编译通过、能跑、只是答案不对）：
//       1) 一开始写成了「数相邻两条之间的上升次数」（a[j] > a[j-1]），
//          这是完全不同的题。题目要的是 a[j] 和 a[i] 比，不是相邻比。
//       2) cnt 必须每条鱼重新清 0，不能用一个全局变量跨鱼累加。
//       3) 输出要在内层循环结束之后 —— 每条鱼只输出一个数。
//          写在内层循环里的话，第 i 条鱼会输出 i-1 个数。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n;
    cin >> n;

    int a[105];
    for (int i = 1; i <= n; i++) cin >> a[i];   // 先全部读完

    for (int i = 1; i <= n; i++) {
        int cnt = 0;                             // 每条鱼重新计数
        for (int j = 1; j < i; j++) {            // 扫它前面所有鱼
            if (a[j] < a[i]) cnt++;              // 比它小就 +1
        }
        cout << cnt << " ";                      // 内层结束后输出，每条鱼一次
    }
    return 0;
}
