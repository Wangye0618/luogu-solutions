// 洛谷 P5728 【深基5.例5】旗鼓相当的对手
// https://www.luogu.com.cn/problem/P5728
// 备注：N 个学生，每人语数英三科。若某对学生的每一科分差都 ≤ 5，
//       且总分分差 ≤ 10，就是「旗鼓相当的对手」。求对数。
//       数据：2 ≤ N ≤ 1000，每科 ≤ 150。
//
//       【模式】枚举所有对
//       【识别信号】题目出现「这两个」「任意两个」「配对」「有几对」
//       【标准写法】for (j = i + 1; j < n; j++)
//                   从 i+1 开始，保证每对只数一次 —— 从 0 开始的话
//                   (1,2) 和 (2,1) 会被数两次，(i,i) 还会自己跟自己配。
//
//       存成绩有两种写法：
//         A. 三个平行数组 ch[] ma[] en[]   ← 本题用这个，最直观
//         B. 二维数组 a[1005][3]           ← 也行，但要多写一层 for k 读入
//       其实二维数组在内存里就是一维的：a[i][k] 等价于 a[i*3 + k]（行优先）。
//       科目只有 2–4 个时，平行数组比二维更好读；科目多了或者要整体排序，才用二维。
//
//       判断顺序：先判三科分差，再判总分分差。
//       三科都满足了再算总分，能省掉大部分不必要的加法。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n;
    cin >> n;

    int ch[1005], ma[1005], en[1005];      // 语文、数学、英语

    for (int i = 0; i < n; i++) {
        cin >> ch[i] >> ma[i] >> en[i];
    }

    int ans = 0;

    for (int i = 0; i < n; i++) {
        for (int j = i + 1; j < n; j++) {          // ← i+1，每对只数一次

            if (abs(ch[i] - ch[j]) <= 5 &&
                abs(ma[i] - ma[j]) <= 5 &&
                abs(en[i] - en[j]) <= 5) {         // ← 三科都满足才继续

                int s1 = ch[i] + ma[i] + en[i];
                int s2 = ch[j] + ma[j] + en[j];
                if (abs(s1 - s2) <= 10) ans++;     // ← 再判总分
            }
        }
    }

    cout << ans << endl;
    return 0;
}
