// 洛谷 P1047 [NOIP2005 普及组] 校门外的树
// https://www.luogu.com.cn/problem/P1047
// 备注：这题的数组不是「存输入的数」，而是「记每个位置的状态」—— 标记数组。
//
//       把马路看成 0..l 共 l+1 个位置，用 a[] 记每个位置有没有树：
//           a[i] = 1 表示有树，a[i] = 0 表示被移走了
//
//       三步：
//         ① 一开始全部置 1
//         ② 每读一个区间 [u, v]，把 a[u]..a[v] 全置 0
//         ③ 数还剩几个 1
//
//       区间有重合也没关系 —— 一个位置被置 0 两次，还是 0，不用去重。
//
//       【模式】标记数组
//       【识别信号】题目出现「某个位置有没有」「被覆盖/涂色」「出现过几次」「去重」
//       【同族题】P1161 开灯、P1554 梦中的统计、P5729 工艺品制作、P1789 插火把
//
//       三处容易错的地方：
//       1) 循环写 i <= l，不是 i < l —— 位置是 0..l，一共 l+1 个。
//       2) 区间 j 从 u 到 v，两端都包含（题目说「包括区域端点处的两棵树」）。
//       3) 数组开够：l ≤ 10000，下标最大 10000，开 a[10005] 更保险。
//
//       另外：区间在 [u, v] 里遍历时另开一个循环变量 k，不要改动 u、v 本身
//       （虽然本题每次会重新 cin，但改输入变量是危险习惯）。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int l, m;
    cin >> l >> m;

    int a[10005], sum = 0;

    // ① 一开始所有位置都有树
    for (int i = 0; i <= l; i++) {
        a[i] = 1;
    }

    // ② 读 m 个区间，把区间内的位置关掉
    for (int j = 1; j <= m; j++) {
        int u, v;
        cin >> u >> v;
        for (int k = u; k <= v; k++) {
            a[k] = 0;
        }
    }

    // ③ 数还剩几个 1
    for (int k = 0; k <= l; k++) {
        if (a[k] == 1) {
            sum++;
        }
    }

    cout << sum << endl;
    return 0;
}
