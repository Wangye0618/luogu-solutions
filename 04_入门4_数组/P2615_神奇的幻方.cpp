// 洛谷 P2615 [NOIP2015 提高组] 神奇的幻方
// https://www.luogu.com.cn/problem/P2615
// 备注：N 为奇数，按四条规则往 N×N 方阵里填 1..N²。
//       本质是「坐标模拟」：不看整个矩阵，只盯着「上一个数填在哪」，推算下一个数的位置。
//
//       四条规则（设 K-1 的位置是 (x, y)）：
//         ① 在第一行但不在最后一列 → K 放到最后一行，列 +1：x = n,    y = y+1
//         ② 在最后一列但不在第一行 → K 放到第一列，  行 -1：x = x-1,  y = 1
//         ③ 既在第一行又在最后一列 → K 放到正下方：       x = x+1,  y 不变
//         ④ 既不在第一行也不在最后一列：
//              右上方 (x-1, y+1) 为 0（空） → 放到右上方
//              右上方已填数                 → 放到正下方 x = x+1
//
//       n = 3 的验证结果（每行每列每条对角线和都是 15）：
//         8 1 6
//         3 5 7
//         4 9 2
//
//       【两个写法要点】
//       1) 用【全局数组】int a[45][45]，全局变量默认初始化为 0，
//          所以不需要手动清空，直接就能用 a[i][j] == 0 判断「这个格子填过没」。
//          （局部数组不初始化就是垃圾值，这也是之前反复踩的坑。）
//       2) 判断顺序用 if / else if 链，四条规则互斥，只能命中一条。
//          写成四个并列的 if 会重复修改坐标。

#include <bits/stdc++.h>
using namespace std;

int a[45][45];   // 全局数组，默认全为 0；N ≤ 39，开 45 够用

int main()
{
    int n;
    cin >> n;

    // 1. 起点：第一行、中间列
    int x = 1;
    int y = (n + 1) / 2;
    a[x][y] = 1;

    // 2. 依次填入 2 .. n*n
    for (int k = 2; k <= n * n; k++) {

        if (x == 1 && y != n) {            // 规则 1：第一行、非最后一列
            x = n;
            y = y + 1;
        }
        else if (y == n && x != 1) {       // 规则 2：最后一列、非第一行
            x = x - 1;
            y = 1;
        }
        else if (x == 1 && y == n) {       // 规则 3：第一行且最后一列
            x = x + 1;
        }
        else {                             // 规则 4：都不在边界
            if (a[x - 1][y + 1] == 0) {    // 右上方是空的
                x = x - 1;
                y = y + 1;
            } else {                       // 右上方已填过
                x = x + 1;
            }
        }

        a[x][y] = k;
    }

    // 3. 输出
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            cout << a[i][j] << " ";
        }
        cout << "\n";
    }

    return 0;
}
