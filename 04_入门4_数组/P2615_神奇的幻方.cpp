// 洛谷 P2615 [NOIP2015 提高组] 神奇的幻方
// https://www.luogu.com.cn/problem/P2615
// 备注：N 为奇数，按四条规则往 N×N 方阵里填 1..N²。
//       本质是「坐标模拟」：不看整个矩阵，只盯「上一个数填在哪」，推算下一个数放哪。
//
//       四条规则（设 K-1 的位置是 (x, y)）：
//         ① 第一行、非最后一列        → 最后一行，列 +1： x = n,   y = y+1
//         ② 最后一列、非第一行        → 第一列，行 -1：  x = x-1, y = 1
//         ③ 第一行且最后一列          → 正下方：        x = x+1
//         ④ 都不在边界：
//              右上方 (x-1, y+1) 是 0（空） → 放右上方
//              右上方已填数                 → 放正下方 x = x+1
//
//       【四个必须对的细节】
//       1) y = (n + 1) / 2 —— 括号不能省。写成 n + 1/2 会变成 n + 0（整数除法）。
//       2) 必须有 for (k = 2; k <= n*n; k++) —— 要填 n² 个数，不是一个。
//       3) 四条规则用 else if 串起来（互斥），不能写成四个并列的 if。
//          并列的话，前一条改了 x、y，后一条会基于新坐标再判断，坐标会乱。
//       4) 规则 4 里检查的是 a[x-1][y+1]（右上方），不是 a[x][y]。
//
//       【全局数组的作用】int a[45][45] 写在 main 外面 → 默认全 0，
//       所以规则 4 的 a[x-1][y+1] == 0 才能正确表示「这个格子还没填过」。
//       写成局部数组就是垃圾值，判断会失效。
//
//       n = 3 的验证结果（每行每列每条对角线和都是 15）：
//         8 1 6
//         3 5 7
//         4 9 2
//
//       【注】规则 3 里的 y = y; 是空操作，可以删掉，不影响结果。

#include <bits/stdc++.h>
using namespace std;

int a[45][45];   // 全局数组，默认全 0；N ≤ 39，开 45 够用

int main()
{
    int n;
    cin >> n;

    // 1. 起点：第一行、中间列
    int x = 1;
    int y = (n + 1) / 2;      // ← 括号不能省
    a[x][y] = 1;

    // 2. 依次填入 2 .. n*n
    for (int k = 2; k <= n * n; k++) {

        if (x == 1 && y != n) {            // 规则 1
            x = n;
            y = y + 1;
        }
        else if (y == n && x != 1) {       // 规则 2
            x = x - 1;
            y = 1;
        }
        else if (x == 1 && y == n) {       // 规则 3：正下方
            x = x + 1;
        }
        else {                             // 规则 4：都不在边界
            if (a[x - 1][y + 1] == 0) {    // 右上方是空的
                x = x - 1;
                y = y + 1;
            } else {                       // 右上方已填过
                x = x + 1;
            }
        }

        a[x][y] = k;
    }

    // 3. 输出整个方阵
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            cout << a[i][j] << " ";
        }
        cout << "\n";
    }

    return 0;
}
