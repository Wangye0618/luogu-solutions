// 洛谷 P5729 【深基5.例7】工艺品制作
// https://www.luogu.com.cn/problem/P5729
// 备注：标记数组的「三维版」，和 P1047 校门外的树 是同一个模式，只多一维。
//       w × x × h 的立方体，每个小方块 a[i][j][k] 记 1（还在）/ 0（被蒸发）。
//       数据：1 ≤ w,x,h ≤ 20，1 ≤ q ≤ 100。
//
//       三步：
//         ① 全部置 1
//         ② q 次切割，每次把 [x1,x2] × [y1,y2] × [z1,z2] 全置 0
//         ③ 数还剩几个 1
//
//       例：4×4×4 切 (1,1,1)-(2,2,2)
//           区间 [1,2] 含两端 → 每维 2 个 → 2×2×2 = 8 块
//           64 - 8 = 56
//
//       【两个坑】
//       1) q 次操作的读入必须写在 for (o = 1; o <= q; o++) 的【里面】。
//          写在外面，就是「同一个操作做 q 遍」，q 行的参数只读了第一行。
//          输入分三段：第一行 w x h；第二行 q；接下来 q 行每行 6 个数
//          （顺序是 x1 y1 z1 x2 y2 z2，不是 x1 x2 y1 y2 z1 z2）。
//       2) 数组不要写成 int a[w][x][h]（变长数组，非标准，且下标只能 0..w-1）。
//          固定开 a[25][25][25]，然后按题目的 1..w 直接当下标用，
//          浪费 a[0] 一点空间，换来「代码里没有 -1 转换」。
//
//       【坐标从几开始，看题目】P1047 是 0..l（位置），本题是 1..w（编号）。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int w, x, h;
    cin >> w >> x >> h;

    int a[25][25][25];

    // ① 全部置 1：每个小方块都还在
    for (int i = 1; i <= w; i++)
        for (int j = 1; j <= x; j++)
            for (int k = 1; k <= h; k++)
                a[i][j][k] = 1;

    // ② q 次切割
    int q;
    cin >> q;

    for (int o = 1; o <= q; o++) {
        int x1, y1, z1, x2, y2, z2;
        cin >> x1 >> y1 >> z1 >> x2 >> y2 >> z2;   // ← 每轮读一次，别放到循环外

        for (int i = x1; i <= x2; i++)
            for (int j = y1; j <= y2; j++)
                for (int k = z1; k <= z2; k++)
                    a[i][j][k] = 0;
    }

    // ③ 数还剩几个 1
    int cnt = 0;
    for (int i = 1; i <= w; i++)
        for (int j = 1; j <= x; j++)
            for (int k = 1; k <= h; k++)
                if (a[i][j][k] == 1) cnt++;

    cout << cnt << endl;
    return 0;
}
