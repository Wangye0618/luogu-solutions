// 洛谷 P5731 【深基5.习6】蛇形方阵
// https://www.luogu.com.cn/problem/P5731
// 备注：从 (1,1) 开始填 1..n²，按「右→下→左→上」顺时针螺旋。
//       走不动（越界 或 格子已填）就右转。
//
//       【新工具：方向数组】
//       把四个方向的「坐标变化量」列成表，就不用写四段 if：
//           int dx[4] = {0,  1,  0, -1};   // 右、下、左、上 的 x 增量
//           int dy[4] = {1,  0, -1,  0};   // 右、下、左、上 的 y 增量
//       dir = 0/1/2/3 表示朝右/下/左/上。
//       走一步： nx = x + dx[dir];  ny = y + dy[dir];
//       右转：   dir = (dir + 1) % 4;        // 3 加 1 后变成 0
//
//       【两个判断都要写】
//           nx < 1 || nx > n || ny < 1 || ny > n     ← 撞墙（越界）
//           a[nx][ny] != 0                            ← 撞到自己填过的格子
//       用 || 不用 && —— 因为判断的是「走不了」，任一条件成立就走不了。
//       如果写成判断「能走」，才用 &&（所有条件都要满足）。
//
//       【为什么不能边填边输出】
//       填的顺序是螺旋的（1→2→3→4 会从 (1,4) 跳到 (2,4)），
//       输出的顺序是按行的。两者不同，所以必须先把数组填完，再按行输出。
//
//       【输出格式】每个数占 3 个字符宽 → cout << setw(3) << a[i][j];
//
//       n = 4 的验证结果：
//           1  2  3  4
//          12 13 14  5
//          11 16 15  6
//          10  9  8  7

#include <bits/stdc++.h>
using namespace std;

int a[20][20];      // n 很小，开 20 够；全局数组默认全 0

int main()
{
    int dx[4] = {0, 1, 0, -1};      // 右 下 左 上 的 x 增量
    int dy[4] = {1, 0, -1, 0};      // 右 下 左 上 的 y 增量

    int x = 1, y = 1;               // 起点左上角
    int dir = 0, n;                 // dir = 0 表示朝右
    cin >> n;

    for (int k = 1; k <= n * n; k++) {
        a[x][y] = k;                // 填当前数

        int nx = x + dx[dir];       // 试着往当前方向走一步
        int ny = y + dy[dir];

        if (nx < 1 || nx > n || ny < 1 || ny > n || a[nx][ny] != 0) {
            dir = (dir + 1) % 4;    // 走不了就右转
            nx = x + dx[dir];
            ny = y + dy[dir];
        }

        x = nx;                     // 确定能走，才更新坐标
        y = ny;
    }

    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            cout << setw(3) << a[i][j];     // 每个数占 3 格
        }
        cout << endl;
    }

    return 0;
}
