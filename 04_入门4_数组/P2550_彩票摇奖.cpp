// 洛谷 P2550 [AHOI2001] 彩票摇奖
// https://www.luogu.com.cn/problem/P2550
// 备注：输入分三段 ——
//         第 1 段：n（彩票张数，n < 1000）
//         第 2 段：7 个中奖号码（1..33，互不相同）
//         第 3 段：接下来 n 行，每行 7 个数，是每张彩票
//       输出 7 个数：中 7 个、6 个、5 个、4 个、3 个、2 个、1 个的彩票张数。
//
//       【两个数组，各管一件事】
//       ① vis[34] —— 标记数组（第 3 次用了）
//          把 7 个中奖号码的位置标成 1。之后查 vis[x] 就知道 x 有没有中。
//          号码范围 1..33，所以开 34（下标 0..33）。
//          这一步把「这张彩票有没有中这个号」从「扫一遍中奖号」变成「查一次表」。
//
//       ② ans[8] —— 计数数组（也叫桶）
//          ans[k] 表示「中了 k 个号」的彩票有几张。
//          注意：这里【下标 k 本身就是信息】，值才是答案。
//          和之前 a[i] 存第 i 个数完全不同 —— 这是新用法。
//          中 0 个的会落到 ans[0]，我们不输出它，所以不影响。
//
//       【注意】cnt 必须在每张彩票开头重新清 0。
//       写在读入循环外面的话，第二张彩票会接着第一张的数继续加。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n;
    cin >> n;                      // 第 1 段：彩票张数

    // ① 把 7 个中奖号码标记起来
    int vis[34] = {0};
    for (int i = 1; i <= 7; i++) {
        int x;
        cin >> x;
        vis[x] = 1;
    }

    // ② 逐张彩票判断
    int ans[8] = {0};              // ans[k] = 中 k 个号的张数
    for (int i = 1; i <= n; i++) {
        int cnt = 0;               // ← 每张彩票重新计数
        for (int j = 1; j <= 7; j++) {
            int x;
            cin >> x;
            if (vis[x] == 1) cnt++;    // 查表：一眼看出中没中
        }
        ans[cnt]++;                // 中 cnt 个的那一档 +1
    }

    // ③ 输出：特等奖（中 7 个）→ 一等奖（6）→ … → 六等奖（1）
    for (int k = 7; k >= 1; k--) {
        cout << ans[k];
        if (k > 1) cout << " ";
    }
    cout << endl;

    return 0;
}
