// 洛谷 P5727 【深基5.例3】冰雹猜想
// https://www.luogu.com.cn/problem/P5727
// 备注：偶数 → 除以 2；奇数 → 乘 3 加 1。一直变到 1，然后把整个序列倒序输出。
//       数据范围 1 ≤ n ≤ 100。
//
//       核心坑：if 后面必须加 else。
//         如果写成
//             if (n % 2 != 0) n = n * 3 + 1;
//             n = n / 2;                 ← 缺 else
//         那奇数时会连做两步（3n+1，再 /2），中间的 3n+1 就被吃掉了。
//         因为奇数时 3n+1 一定是偶数，所以「下一个值」算出来仍然对 ——
//         代码能跑、不报错，只是序列里少了那个数。这种「对一半」的 bug 最难查。
//         例：n = 20，正确序列是 20→10→5→16→8→4→2→1，
//             缺 else 会变成 20→10→5→8→4→2→1，16 没了。
//
//       另外三处：
//       1) 要把 n 本身也存进去（倒序输出时它在最后），所以进循环前先存一次。
//       2) 倒序输出从 i-1 开始 —— i 是「下一个要写的位置」，最后一个有值的下标是 i-1。
//       3) 数组要开够：n ≤ 100 里最长的是 n = 97，序列长度 119（含 97 和 1），
//          所以 a[100] 会越界，开 a[200]。
//
//       存数组的写法用拆开的两行，比 a[i++] 更好读：
//           a[i] = n;  i++;

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int n;
    cin >> n;

    int a[200], i = 0;

    a[i] = n;  i++;                  // 先把 n 本身存进去
    while (n != 1) {
        if (n % 2 != 0) n = n * 3 + 1;
        else            n = n / 2;   // ← else 不能少
        a[i] = n;  i++;
    }

    for (int j = i - 1; j >= 0; j--) {
        cout << a[j] << " ";
    }
    return 0;
}
