// 洛谷 P1427 小鱼的数字游戏
// https://www.luogu.com.cn/problem/P1427
// 备注：读入一串整数，遇到 0 停止（0 不算进答案），倒序输出。
//       用 n 记录「最后一个非零元素的下标」，再从 n 倒着输出 —— 比另开计数器简洁。
//
//       走 1 2 3 0：i=0 读 1 → n=0；i=1 读 2 → n=1；i=2 读 3 → n=2；
//                  i=3 读 0 → break（n 仍是 2）。从 a[2] 倒着输出 → 3 2 1。
//
//       踩过的坑：
//       1) int a[100] 配 for (i = 0; i <= 100; i++) → a[100] 越界。
//          数列最多 100 个数，加上结尾那个 0 要 101 个位置，开 a[105]。
//       2) n 没初始化 —— 如果第一个输入就是 0，循环立刻 break，n 还是垃圾值，
//          第二层循环从乱数开始。初始化成 -1：没有数时 for 一次都不进，什么也不输出，
//          正好符合题意。

#include <bits/stdc++.h>
using namespace std;
int main()
{
    int a[105], n = -1;              // a 开够；n 初始化为 -1

    for (int i = 0; i < 105; i++) {
        cin >> a[i];
        if (a[i] == 0) break;        // 0 是结束标记，不算
        n = i;                       // 记住最后一个非零元素的下标
    }

    for (int i = n; i >= 0; i--) {
        cout << a[i] << " ";
    }
    return 0;
}
